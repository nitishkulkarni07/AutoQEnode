import { CircuitGate, CircuitDefinition } from '../../types';

export function generateCircuit(
  encoding: 'basis' | 'angle' | 'amplitude' | 'dense_angle' | 'data_reuploading' | 'hybrid',
  numFeatures: number,
  numQubits: number,
  includeAnsatz: boolean = true,
  ansatzLayers: number = 1
): CircuitDefinition {
  const gates: CircuitGate[] = [];
  let gateIdCounter = 0;
  const nextId = () => `g_${gateIdCounter++}`;

  let maxCol = 0;
  const qubitNextCol = new Array(numQubits).fill(0);

  const addGate = (name: string, qubits: number[], controlQubits?: number[], params?: string[]) => {
    let targetCol = 0;
    const allQubits = [...qubits, ...(controlQubits || [])];
    for (const q of allQubits) {
      if (q < numQubits) {
        targetCol = Math.max(targetCol, qubitNextCol[q]);
      }
    }

    const g: CircuitGate = {
      id: nextId(),
      name,
      qubits,
      controlQubits,
      params,
      column: targetCol,
    };
    gates.push(g);

    for (const q of allQubits) {
      if (q < numQubits) {
        qubitNextCol[q] = targetCol + 1;
      }
    }
    maxCol = Math.max(maxCol, targetCol + 1);
  };

  if (encoding === 'basis') {
    for (let q = 0; q < Math.min(numQubits, numFeatures); q++) {
      if (q % 2 === 0) addGate('X', [q]);
    }
  } else if (encoding === 'angle') {
    for (let q = 0; q < Math.min(numQubits, numFeatures); q++) {
      addGate('Ry', [q], undefined, [`θ_${q}`]);
    }
  } else if (encoding === 'dense_angle') {
    for (let q = 0; q < Math.min(numQubits, Math.ceil(numFeatures / 2)); q++) {
      addGate('Ry', [q], undefined, [`x_${2*q}·π`]);
      addGate('Rz', [q], undefined, [`x_${2*q+1}·π`]);
    }
  } else if (encoding === 'data_reuploading') {
    for (let q = 0; q < Math.min(numQubits, numFeatures); q++) {
      addGate('Ry', [q], undefined, [`x_${q}·π`]);
    }
  } else if (encoding === 'amplitude') {
    const logQubits = Math.max(1, Math.min(numQubits, Math.ceil(Math.log2(numFeatures || 2))));
    addGate('Ry', [0], undefined, ['α_0']);
    for (let q = 1; q < logQubits; q++) {
      addGate('CX', [q], [q - 1]);
      addGate('Ry', [q], undefined, [`α_${q}`]);
      addGate('CX', [q], [q - 1]);
    }
  } else if (encoding === 'hybrid') {
    if (numQubits > 0) addGate('X', [0]);
    if (numQubits > 1) addGate('Ry', [1], undefined, ['θ_cont']);
    if (numQubits > 2) {
      addGate('Ry', [2], undefined, ['α_corr']);
      if (numQubits > 3) {
        addGate('CX', [3], [2]);
        addGate('Ry', [3], undefined, ['α_corr2']);
      }
    }
  }

  if (includeAnsatz) {
    for (let l = 0; l < ansatzLayers; l++) {
      for (let q = 0; q < numQubits; q++) {
        addGate('Ry', [q], undefined, [`w_${l}_${q}_0`]);
        addGate('Rz', [q], undefined, [`w_${l}_${q}_1`]);
      }

      if (numQubits > 1) {
        for (let q = 0; q < numQubits - 1; q++) {
          addGate('CX', [q + 1], [q]);
        }
        if (numQubits > 2) {
          addGate('CX', [0], [numQubits - 1]);
        }
      }
      if (encoding === 'data_reuploading') {
        for (let q = 0; q < Math.min(numQubits, numFeatures); q++) {
          addGate('Ry', [q], undefined, [`x_${q}·π`]);
        }
      }
    }

    for (let q = 0; q < numQubits; q++) {
      addGate('Measure', [q]);
    }
  }

  let singleQubitGates = 0;
  let twoQubitGates = 0;

  for (const g of gates) {
    if (g.name === 'Measure') continue;
    if (g.name === 'CX' || g.name === 'CZ' || g.name === 'SWAP') {
      twoQubitGates++;
    } else {
      singleQubitGates++;
    }
  }

  const depth = maxCol;
  const totalGates = singleQubitGates + twoQubitGates;
  const estimatedError = parseFloat((singleQubitGates * 0.001 + twoQubitGates * 0.015).toFixed(4));

  let qasm2 = `// Parameter placeholders are visual labels; all rotation angles below are pi/4 examples, NOT the fitted circuit.\n// Generated by AutoQEncode v2.4 (Research Platform)\nOPENQASM 2.0;\ninclude "qelib1.inc";\nqreg q[${numQubits}];\ncreg c[${numQubits}];\n\n`;
  for (const g of gates) {
    if (g.name === 'Measure') {
      qasm2 += `measure q[${g.qubits[0]}] -> c[${g.qubits[0]}];\n`;
    } else if (g.name === 'CX') {
      qasm2 += `cx q[${g.controlQubits?.[0]}], q[${g.qubits[0]}];\n`;
    } else if (g.name === 'Ry') {
      qasm2 += `ry(${'pi/4'}) q[${g.qubits[0]}];\n`;
    } else if (g.name === 'Rz') {
      qasm2 += `rz(${'pi/4'}) q[${g.qubits[0]}];\n`;
    } else if (g.name === 'X') {
      qasm2 += `x q[${g.qubits[0]}];\n`;
    } else if (g.name === 'H') {
      qasm2 += `h q[${g.qubits[0]}];\n`;
    }
  }

  let qasm3 = `// Parameter placeholders are visual labels; all rotation angles below are pi/4 examples, NOT the fitted circuit.\n// Generated by AutoQEncode v2.4 (OpenQASM 3.0)\nOPENQASM 3.0;\ninclude "stdgates.inc";\nqubit[${numQubits}] q;\nbit[${numQubits}] c;\n\n`;
  for (const g of gates) {
    if (g.name === 'Measure') {
      qasm3 += `c[${g.qubits[0]}] = measure q[${g.qubits[0]}];\n`;
    } else if (g.name === 'CX') {
      qasm3 += `cx q[${g.controlQubits?.[0]}], q[${g.qubits[0]}];\n`;
    } else if (g.name === 'Ry') {
      qasm3 += `ry(${'pi/4'}) q[${g.qubits[0]}];\n`;
    } else if (g.name === 'Rz') {
      qasm3 += `rz(${'pi/4'}) q[${g.qubits[0]}];\n`;
    } else if (g.name === 'X') {
      qasm3 += `x q[${g.qubits[0]}];\n`;
    } else if (g.name === 'H') {
      qasm3 += `h q[${g.qubits[0]}];\n`;
    }
  }

  const complexityMap = {
    basis: {
      qubitScaling: 'O(N) qubits',
      depthScaling: 'O(1) state prep depth',
      twoQubitScaling: '0 two-qubit gates (encoding only)',
      suitableData: 'Discrete binary flags, categorical indices, low-cardinality features.',
    },
    angle: {
      qubitScaling: 'O(N) qubits',
      depthScaling: 'O(1) parallel rotation depth',
      twoQubitScaling: '0 two-qubit gates (encoding only)',
      suitableData: 'Bounded continuous numerical features with natural periodic or trigonometric symmetries.',
    },
    amplitude: {
      qubitScaling: 'O(log2(N)) logarithmic qubits',
      depthScaling: 'O(2^n) exponential state prep depth without ancilla',
      twoQubitScaling: 'O(2^n) CNOT ladder decomposition',
      suitableData: 'Dense, highly correlated numerical arrays, image patches, high-dimensional vectors.',
    },
    dense_angle: {
      qubitScaling: 'O(ceil(N/2)) qubits',
      depthScaling: '2 serial rotations per wire',
      twoQubitScaling: '0 entangling gates in embedding',
      suitableData: 'Pairs of bounded real-valued features; compact continuous datasets.',
    },
    data_reuploading: {
      qubitScaling: 'O(N) qubits for the displayed parallel map',
      depthScaling: 'O(L) repeated embedding stages',
      twoQubitScaling: '0 in embedding; ansatz gates scale with L',
      suitableData: 'Non-linear classification where repeated data/variational interactions help.',
    },
    hybrid: {
      qubitScaling: 'Adaptive O(K_discrete + K_angle + log2(K_amp))',
      depthScaling: 'Controlled O(D_hybrid <= Budget)',
      twoQubitScaling: 'Optimized via sparse routing',
      suitableData: 'Heterogeneous real-world tabular data containing mixed continuous and discrete features.',
    },
  };

  return {
    encodingType: encoding,
    numQubits,
    depth,
    totalGates,
    singleQubitGates,
    twoQubitGates,
    estimatedError,
    gates,
    qasm2,
    qasm3,
    complexity: complexityMap[encoding],
  };
}
